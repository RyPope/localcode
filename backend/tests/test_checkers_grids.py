@pytest.mark.parametrize(("slug", "args", "expected", "valid", "invalid"), CASES)
def test_checker(slug: str, args: list[Any], expected: Any, valid: list[Any], invalid: list[Any]) -> None:
    mode = f"checker:{slug}"
    for answer in valid:
        assert judge(expected, answer, mode, args), answer
    for answer in invalid:
        assert not judge(expected, answer, mode, args), answer


def test_every_slug_has_a_different_valid_answer() -> None:
    slugs = {case[0] for case in CASES}
    with_alternative = {slug for slug, *_, valid, _ in CASES if len(valid) > 1}
    assert slugs == with_alternative
