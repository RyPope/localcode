"""Drop generated test cases that violate a problem's constraints.

LeetCodeDataset's cases were generated by running a Python reference on synthetic inputs. Some of
those inputs break the problem's stated constraints (values beyond 32-bit range, impossible inputs).
Python tolerates them, but typed languages cannot, so correct Java/C++/Kotlin code would fail them.
"""

import hashlib
import json
import re
from typing import Any

from localcode.judging.types import Case

_INT_RANGES = {
    "int": 2**31,
    "Integer": 2**31,
    "long": 2**63,
    "Long": 2**63,
    "short": 2**15,
    "Short": 2**15,
    "byte": 2**7,
    "Byte": 2**7,
}
_FLOATS = {"double", "Double", "float", "Float"}
_BOOLS = {"boolean", "Boolean"}
_CHARS = {"char", "Character"}
_NODES = {"ListNode", "TreeNode"}
NODE_RETURNS = {"ListNode", "TreeNode"}


def case_key(args: list[Any]) -> str:
    """Stable identifier for a case's inputs (used by the shipped exclusion list)."""
    return hashlib.sha1(json.dumps(args, separators=(",", ":")).encode()).hexdigest()[:16]


def _is_int(v: Any) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _node_values_fit(v: Any) -> bool:
    return isinstance(v, list) and all(x is None or (_is_int(x) and -(2**31) <= x < 2**31) for x in v)


def fits_java_type(value: Any, java_type: str) -> bool:
    """Whether `value` (JSON) can be represented as `java_type`. Unknown types are accepted."""
    t = java_type.strip()
    if t.endswith("[]"):
        return isinstance(value, list) and all(fits_java_type(v, t[:-2]) for v in value)
    generic = re.fullmatch(r"(?:List|ArrayList|Collection|Set|Iterable)<(.+)>", t)
    if generic:
        return isinstance(value, list) and all(fits_java_type(v, generic.group(1)) for v in value)
    if t in _INT_RANGES:
        bound = _INT_RANGES[t]
        return _is_int(value) and -bound <= value < bound
    if t in _FLOATS:
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if t in _BOOLS:
        return isinstance(value, bool)
    if t in _CHARS:
        return isinstance(value, str) and len(value) == 1
    if t == "String":
        return isinstance(value, str)
    if t in _NODES:
        return _node_values_fit(value)
    return True


def filter_cases(cases: list[Case], ret: str, java_sig: dict | None, excluded: set[str]) -> list[Case]:
    """Keep only cases that every supported language can represent and that are not known-bad."""
    kept = []
    for c in cases:
        if c["expected"] is None and ret not in NODE_RETURNS:
            continue  # the reference fell through: the input has no valid answer
        if java_sig is not None:
            if len(c["args"]) != len(java_sig["params"]):
                continue
            if not all(fits_java_type(a, p["type"]) for a, p in zip(c["args"], java_sig["params"], strict=False)):
                continue
            if java_sig["ret"] != "void" and not fits_java_type(c["expected"], java_sig["ret"]):
                continue
        if excluded and case_key(c["args"]) in excluded:
            continue
        kept.append(c)
    return kept
